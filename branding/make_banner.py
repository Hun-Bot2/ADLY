"""Generate branding/banner.svg (README banner). Stdlib only; render with:

    python3 branding/make_banner.py && rsvg-convert -w 1600 branding/banner.svg -o branding/banner.png

Layout: text block left, a 14-week activity grid ("잔디") card right, both centred on the same midline with
PAD px above and below. Colours follow the app's Tableau palette. The grid pattern is fixed (seeded), not real data.
"""
import random
from pathlib import Path

W, PAD = 1600, 70            # top/bottom padding: 116px earlier, reduced by 40% (user request 2026-11-03)
SIDE = 140                   # left/right margin
CELL, GAP, WEEKS = 20, 6, 14
LEVELS = ["#e5e8eb", "#c5d3e3", "#8fadcc", "#5a86b4", "#3d6188"]
FONT = "Apple SD Gothic Neo, Helvetica Neue, sans-serif"

# Measured ink height of the text block below (eyebrow row to chip bottom); the card matches it.
TEXT_H = 258
H = TEXT_H + 2 * PAD


def grid_levels():
    rng = random.Random(20261103)
    rows = []
    for week in range(WEEKS):
        trend = week / (WEEKS - 1)            # more activity in recent weeks
        rows.append([min(4, max(0, round(rng.random() * 2.6 + trend * 2.4 - 0.9))) for _ in range(7)])
    return rows


def icon(x, y, size):
    s = size / 824
    return (f'<g transform="translate({x} {y}) scale({s:.5f}) translate(-100 -100)">'
            '<rect x="100" y="100" width="824" height="824" rx="186" fill="url(#icon)"/>'
            '<path d="M318 742 L512 268 L706 742" fill="none" stroke="#fff" stroke-width="92" stroke-linecap="round" stroke-linejoin="round"/>'
            '<path d="M392 598 L470 672 L640 500" fill="none" stroke="#edc948" stroke-width="72" stroke-linecap="round" stroke-linejoin="round"/>'
            '</g>')


def main():
    top = PAD
    # Text block: eyebrow row (icon + name), headline, subline, platform chips. Baselines are relative to `top`.
    text = [
        icon(SIDE, top, 44),
        f'<text x="{SIDE + 58}" y="{top + 31}" font-size="26" font-weight="700" fill="#4e79a7" letter-spacing=".5">ALDY · Algorithm Daily</text>',
        f'<text x="{SIDE - 4}" y="{top + 132}" font-size="64" font-weight="700" fill="#191f28" letter-spacing="-1">매일 풀 문제를, 내 기록으로.</text>',
        f'<text x="{SIDE}" y="{top + 186}" font-size="27" font-weight="500" fill="#4e5968">풀이 기록을 읽어 오늘의 문제와 복습을 계획하는 로컬 학습 앱</text>',
    ]
    chips, x = [], SIDE
    for label, width, accent in [("LeetCode", 128, False), ("Codeforces", 150, False), ("AtCoder", 118, False), ("macOS", 108, True)]:
        fill, stroke, colour = ("#e9eff6", "none", "#3d6188") if accent else ("#fff", "#e5e8eb", "#4e5968")
        chips.append(f'<rect x="{x}" y="{top + 214}" width="{width}" height="44" rx="22" fill="{fill}" stroke="{stroke}"/>'
                     f'<text x="{x + width / 2}" y="{top + 243}" text-anchor="middle" font-size="22" font-weight="600" fill="{colour}">{label}</text>')
        x += width + 12

    # Activity card, right-aligned at the side margin, same height as the text block.
    grid_w = WEEKS * CELL + (WEEKS - 1) * GAP
    card_w, card_h = grid_w + 48, TEXT_H
    cx, cy = W - SIDE - card_w, top
    cells = []
    gx, gy = cx + 24, cy + 62
    for week, column in enumerate(grid_levels()):
        for day, level in enumerate(column):
            cells.append(f'<rect x="{gx + week * (CELL + GAP)}" y="{gy + day * (CELL + GAP)}" width="{CELL}" height="{CELL}" rx="5" fill="{LEVELS[level]}"/>')
    legend_x = cx + card_w - 24 - 190   # 적음(36) + 40 + 5 swatches x 22 + 4 + 많음(36)
    legend = [f'<text x="{legend_x}" y="{cy + 41}" font-size="17" fill="#8b95a1">적음</text>']
    for i, colour in enumerate(LEVELS):
        legend.append(f'<rect x="{legend_x + 40 + i * 22}" y="{cy + 27}" width="16" height="16" rx="4" fill="{colour}"/>')
    legend.append(f'<text x="{legend_x + 40 + 5 * 22 + 4}" y="{cy + 41}" font-size="17" fill="#8b95a1">많음</text>')
    card = [
        f'<rect x="{cx}" y="{cy}" width="{card_w}" height="{card_h}" rx="20" fill="#fff" filter="url(#lift)"/>',
        f'<text x="{cx + 24}" y="{cy + 42}" font-size="21" font-weight="700" fill="#191f28">최근 14주 풀이</text>',
        *legend, *cells,
    ]

    svg = f'''<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}">
  <!-- Generated by branding/make_banner.py; edit the script, not this file. -->
  <defs>
    <linearGradient id="icon" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#5a86b4"/><stop offset="1" stop-color="#3d6188"/></linearGradient>
    <filter id="lift" x="-20%" y="-20%" width="140%" height="150%"><feDropShadow dx="0" dy="10" stdDeviation="16" flood-color="#1f3b5c" flood-opacity=".10"/></filter>
  </defs>
  <rect width="{W}" height="{H}" rx="28" fill="#f3f6fa"/>
  <g font-family="{FONT}">
    {"".join(text)}
    {"".join(chips)}
    {"".join(card)}
  </g>
</svg>
'''
    Path(__file__).with_name("banner.svg").write_text(svg, encoding="utf-8")


if __name__ == "__main__":
    main()
